create or replace function public.trisar_flug_herkunft_mit_ort()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_ort text;
begin
  if new.flight_origin is not null and new.flight_origin ~ '^[A-Z]{3}$' then
    select ort into v_ort from public.flughafen_orte where iata = new.flight_origin;
    if v_ort is not null then
      new.flight_origin := v_ort || ' (' || new.flight_origin || ')';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists trg_flug_herkunft_mit_ort on public.jobs;
create trigger trg_flug_herkunft_mit_ort
  before insert or update of flight_origin on public.jobs
  for each row execute function public.trisar_flug_herkunft_mit_ort();

-- Fahrten ab gestern nachziehen (aeltere bleiben, wie sie waren).
