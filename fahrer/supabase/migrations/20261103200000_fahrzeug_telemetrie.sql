-- Fahrzeugdaten aus dem OBD-Tracker (Teltonika FMB010), 03.11.2026.
-- vehicle_telemetry_live    letzter Stand je Fahrer (Zuendung, Drehzahl, Tank, Spannung, km-Stand ...)
-- vehicle_telemetry_events  vom Geraet gemeldete Ereignisse (Fahrtbeginn/-ende, Leerlauf,
--                           starkes Bremsen, Abstecken, Zuendung an/aus ...)
-- Schreibt nur das Gateway (service_role). Disposition liest alles, Fahrer das eigene Fahrzeug.

begin;

create table if not exists public.vehicle_telemetry_live (
  driver_id uuid primary key references public.profiles(id) on delete cascade,
  imei text,
  captured_at timestamptz,
  ignition boolean,
  movement boolean,
  rpm integer,
  obd_speed_kph integer,
  fuel_level_pct integer,
  coolant_c integer,
  engine_load_pct integer,
  throttle_pct integer,
  engine_runtime_s integer,
  fuel_rate_lph numeric(8,2),
  fuel_used_gps_l numeric(10,3),
  ext_voltage_v numeric(6,3),
  battery_voltage_v numeric(6,3),
  control_module_voltage_v numeric(6,3),
  gsm_signal integer,
  total_odometer_km numeric(12,3),
  trip_odometer_km numeric(12,3),
  oem_mileage_km numeric(12,1),
  oem_fuel_l numeric(8,1),
  dtc_count integer,
  mil_distance_km integer,
  oil_temp_c integer,
  ambient_c integer,
  vin text,
  fault_codes text,
  raw_io jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.vehicle_telemetry_events (
  id bigint generated by default as identity primary key,
  driver_id uuid not null references public.profiles(id) on delete cascade,
  imei text,
  job_id uuid,
  event_type text not null,
  value numeric,
  lat double precision,
  lng double precision,
  captured_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists idx_vehicle_telemetry_events_driver_time
  on public.vehicle_telemetry_events(driver_id, captured_at desc);

create or replace function public.vehicle_telemetry_live_touch()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists trg_vehicle_telemetry_live_touch on public.vehicle_telemetry_live;
create trigger trg_vehicle_telemetry_live_touch
  before update on public.vehicle_telemetry_live
  for each row execute function public.vehicle_telemetry_live_touch();

alter table public.vehicle_telemetry_live enable row level security;
alter table public.vehicle_telemetry_events enable row level security;

drop policy if exists dispo_alles on public.vehicle_telemetry_live;
create policy dispo_alles on public.vehicle_telemetry_live
  for all to authenticated using (public.ist_dispo()) with check (public.ist_dispo());
drop policy if exists fahrer_eigenes_fahrzeug on public.vehicle_telemetry_live;
create policy fahrer_eigenes_fahrzeug on public.vehicle_telemetry_live
  for select to authenticated using (driver_id = auth.uid());

drop policy if exists dispo_alles on public.vehicle_telemetry_events;
create policy dispo_alles on public.vehicle_telemetry_events
  for all to authenticated using (public.ist_dispo()) with check (public.ist_dispo());
drop policy if exists fahrer_eigene_ereignisse on public.vehicle_telemetry_events;
create policy fahrer_eigene_ereignisse on public.vehicle_telemetry_events
  for select to authenticated using (driver_id = auth.uid());

grant select on public.vehicle_telemetry_live, public.vehicle_telemetry_events to authenticated;
grant all on public.vehicle_telemetry_live, public.vehicle_telemetry_events to service_role;
grant usage, select on sequence public.vehicle_telemetry_events_id_seq to service_role;

-- Live-Aktualisierung in den Apps (postgres_changes)
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    begin
      alter publication supabase_realtime add table public.vehicle_telemetry_live;
    exception when duplicate_object then null; end;
    begin
      alter publication supabase_realtime add table public.vehicle_telemetry_events;
    exception when duplicate_object then null; end;
  end if;
end $$;

commit;
